using System.ComponentModel;
using System.Globalization;

namespace Plumix.Slang;

/// <summary>
/// Bridge between a Slang.Net generated translations class and the widget-level API of this package.
///
/// Slang.Net emits its whole surface as static members on the <c>[Translations]</c> partial class,
/// so the contract is expressed with static abstract members: implementing it on the partial makes
/// <see cref="TranslationProvider{T}"/>, <see cref="Translations{T}"/> and <see cref="LocaleSettings{T}"/>
/// usable without reflection (and therefore trimming/AOT safe).
///
/// Only two members need hand-written glue; <c>BaseCulture</c>, <c>SupportedCultures</c> and
/// <c>SetCulture</c> are already generated with matching signatures:
/// <code>
/// [Translations(InputFileName = "strings")]
/// public partial class Strings : ITranslations&lt;Strings&gt;
/// {
///     static Strings ITranslations&lt;Strings&gt;.CurrentTranslations =&gt; Instance.Root;
///     static INotifyPropertyChanged ITranslations&lt;Strings&gt;.ChangeSource =&gt; Instance;
/// }
/// </code>
/// </summary>
/// <typeparam name="TSelf">The generated translations class itself.</typeparam>
public interface ITranslations<TSelf>
    where TSelf : ITranslations<TSelf>
{
    /// <summary>
    /// The translations tree for <see cref="CultureInfo.CurrentUICulture"/>
    /// (Slang.Net's <c>Instance.Root</c>).
    /// </summary>
    static abstract TSelf CurrentTranslations { get; }

    /// <summary>
    /// Raises <see cref="INotifyPropertyChanged.PropertyChanged"/> whenever the culture changes
    /// (Slang.Net's <c>Instance</c>). <see cref="TranslationProvider{T}"/> subscribes to it.
    /// </summary>
    static abstract INotifyPropertyChanged ChangeSource { get; }

    /// <summary>The culture the translations fall back to. Generated by Slang.Net.</summary>
    static abstract CultureInfo BaseCulture { get; }

    /// <summary>Every culture the generated class carries translations for. Generated by Slang.Net.</summary>
    static abstract IReadOnlyList<CultureInfo> SupportedCultures { get; }

    /// <summary>
    /// Switches the active culture and notifies <see cref="ChangeSource"/>. Generated by Slang.Net.
    /// </summary>
    /// <param name="culture">The culture to activate.</param>
    /// <param name="uiOnly">
    /// When <c>true</c>, only <see cref="CultureInfo.CurrentUICulture"/> is changed and
    /// <see cref="CultureInfo.CurrentCulture"/> (number/date formatting) is left alone.
    /// </param>
    static abstract void SetCulture(CultureInfo culture, bool uiOnly = false);
}
